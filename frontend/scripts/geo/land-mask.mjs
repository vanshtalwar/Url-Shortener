// Generates src/app/experience/land-mask.ts: which 2.5° cells of the globe are land, as base64 bits.
// The landing globe draws a dot per land cell, so the page needs no map download and no d3 at runtime.
// Data: world-atlas land-110m (Natural Earth, public domain). Run from frontend/: node scripts/geo/land-mask.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { geoContains } from 'd3-geo';
import { feature } from 'topojson-client';

const STEP = 2.5; // degrees per cell
const COLUMNS = 360 / STEP; // longitude −180 … 180, west to east
const ROWS = 180 / STEP; // latitude 90 … −90, north to south

const topology = JSON.parse(readFileSync(new URL('../../node_modules/world-atlas/land-110m.json', import.meta.url), 'utf8'));
const land = feature(topology, topology.objects.land);

const bytes = new Uint8Array(Math.ceil((COLUMNS * ROWS) / 8));
let count = 0;
for (let row = 0; row < ROWS; row++) {
  for (let column = 0; column < COLUMNS; column++) {
    const centre = [-180 + (column + 0.5) * STEP, 90 - (row + 0.5) * STEP];
    if (!geoContains(land, centre)) continue;
    const bit = row * COLUMNS + column;
    bytes[bit >> 3] |= 1 << (bit & 7);
    count++;
  }
}

const out = new URL('../../src/app/experience/land-mask.ts', import.meta.url);
writeFileSync(out, `// GENERATED by scripts/geo/land-mask.mjs from world-atlas land-110m (Natural Earth, public domain). Do not edit.

/** Land cells of a ${STEP}° grid: ${COLUMNS} columns (longitude −180 → 180) × ${ROWS} rows (latitude 90 → −90), row-major bits, base64. ${count} land cells. */
export const LAND_MASK = '${Buffer.from(bytes).toString('base64')}';
export const LAND_STEP = ${STEP};
`);
console.log(`${count} land cells of ${COLUMNS * ROWS} → ${out.pathname}`);
